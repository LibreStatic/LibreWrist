import java.io.PrintWriter;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/**
 * Generates engine/src/main/resources/io/openshm/patcher/engine/framework-ids.txt from the public
 * Android SDK jar (the ids of the framework attrs and styles are public API constants).
 *
 * Usage: java engine/tools/GenFrameworkIds.java <android.jar> <output file>
 *
 * Output lines: "<type>/<name>=<hex id>", sorted; types: attr, style.
 */
public class GenFrameworkIds {
    public static void main(String[] args) throws Exception {
        if (args.length != 2) {
            System.err.println("usage: java GenFrameworkIds.java <android.jar> <output file>");
            System.exit(2);
        }
        List<String> lines = new ArrayList<>();
        try (URLClassLoader cl = new URLClassLoader(new URL[] {Path.of(args[0]).toUri().toURL()}, null)) {
            for (String type : new String[] {"attr", "style"}) {
                Class<?> c = Class.forName("android.R$" + type, true, cl);
                for (Field f : c.getFields()) {
                    if (!Modifier.isStatic(f.getModifiers()) || f.getType() != int.class) continue;
                    lines.add(type + "/" + (type.equals("style") ? f.getName().replace('_', '.') : f.getName()) + "=" + Integer.toHexString(f.getInt(null)));
                }
            }
        }
        Collections.sort(lines);
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(Path.of(args[1]), StandardCharsets.UTF_8))) {
            w.print("# Generated by engine/tools/GenFrameworkIds.java from the public Android SDK jar. Do not edit.\n");
            for (String l : lines) w.print(l + "\n");
        }
    }
}
